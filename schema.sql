-- این دستورات را در SQL Editor پروژه Supabase اجرا کنید.
create table if not exists public.projects (
 id bigint generated by default as identity primary key,
 title text not null,
 category text not null default 'website' check(category in ('website','desktop','other')),
 description text not null, details text default '', project_url text,
 cover_url text, images jsonb not null default '[]'::jsonb,
 published boolean not null default true, created_at timestamptz not null default now()
);
alter table public.projects enable row level security;
create policy "public read published" on public.projects for select to anon,authenticated using(published=true);
create policy "admins insert" on public.projects for insert to authenticated with check(true);
create policy "admins update" on public.projects for update to authenticated using(true) with check(true);
create policy "admins delete" on public.projects for delete to authenticated using(true);
insert into storage.buckets(id,name,public) values('project-images','project-images',true) on conflict(id) do nothing;
create policy "public view images" on storage.objects for select to anon,authenticated using(bucket_id='project-images');
create policy "authenticated upload images" on storage.objects for insert to authenticated with check(bucket_id='project-images');
create policy "authenticated update images" on storage.objects for update to authenticated using(bucket_id='project-images') with check(bucket_id='project-images');
create policy "authenticated delete images" on storage.objects for delete to authenticated using(bucket_id='project-images');
